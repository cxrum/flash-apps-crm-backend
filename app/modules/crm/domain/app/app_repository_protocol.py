from __future__ import annotations

from typing import Protocol

from app.modules.crm.domain.app.CrmAppEntity import CrmAppEntity
from app.modules.crm.domain.pagination import Pagination


class CrmAppRepositoryProtocol(Protocol):
    def save(self, entity: CrmAppEntity) -> CrmAppEntity: ...
    def delete(self, app_id: int) -> CrmAppEntity: ...
    def save_many(self, entities: list[CrmAppEntity]) -> list[CrmAppEntity]: ...
    def get_by_id(self, app_id: int) -> CrmAppEntity | None: ...
    def get_by_slug(self, code_slug: str) -> CrmAppEntity | None: ...
    def list_all(self, *, pagination: Pagination | None = None) -> list[CrmAppEntity]: ...
