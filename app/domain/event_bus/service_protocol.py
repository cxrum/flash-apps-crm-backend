from __future__ import annotations

from collections.abc import Sequence
from typing import Protocol

from app.domain.event_bus.entity import DomainEventMessage


class EventMessageHandler(Protocol):
    def handle(self, message: DomainEventMessage) -> None: ...

class AsyncEventMessageHandler(Protocol):
    async def handle(self, message: DomainEventMessage) -> None: ...

class IMessageQueue(Protocol):
    def enqueue(self, message: DomainEventMessage) -> None: ...
    def dequeue(self) -> DomainEventMessage | None: ...
    def drain(self) -> list[DomainEventMessage]: ...
    def size(self) -> int: ...

class IAsyncMessageQueue(Protocol):
    async def enqueue(self, message: DomainEventMessage) -> None: ...
    async def dequeue(self) -> DomainEventMessage: ...
    def size(self) -> int: ...

class IEventBus(Protocol):
    def subscribe(self, event_name: str, handler: EventMessageHandler) -> None: ...
    def unsubscribe(self, event_name: str, handler: EventMessageHandler) -> None: ...
    def publish(self, message: DomainEventMessage) -> None: ...
    def publish_many(self, messages: Sequence[DomainEventMessage]) -> None: ...

class IAsyncEventBus(Protocol):
    def subscribe(
        self,
        event_name: str,
        handler: AsyncEventMessageHandler | EventMessageHandler,
    ) -> None: ...
    def unsubscribe(
        self,
        event_name: str,
        handler: AsyncEventMessageHandler | EventMessageHandler,
    ) -> None: ...
    async def publish(self, message: DomainEventMessage) -> None: ...
    async def publish_many(self, messages: Sequence[DomainEventMessage]) -> None: ...
    async def start(self) -> None: ...
    async def stop(self) -> None: ...