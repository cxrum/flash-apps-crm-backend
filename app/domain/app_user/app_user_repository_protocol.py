from __future__ import annotations

from typing import Protocol

from app.domain.app_user.CrmAppUserEntity import CrmAppUserEntity


class CrmAppUserRepositoryProtocol(Protocol):
    def save(self, entity: CrmAppUserEntity) -> None: ...
    def save_many(self, entities: list[CrmAppUserEntity]) -> None: ...
    def get_by_id(self, app_user_id: int) -> CrmAppUserEntity | None: ...
    def get_by_external_id(self, app_platform_id: int, crm_user_id: str) -> CrmAppUserEntity | None: ...
    def list_by_platform_id(self, app_platform_id: int) -> list[CrmAppUserEntity]: ...
