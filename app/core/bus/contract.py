from __future__ import annotations

from collections.abc import Sequence
from typing import Protocol

from app.core.bus.type import EventMessage, ExceptionEvent


class EventMessageHandler(Protocol):
    def handle(self, message: EventMessage) -> None: ...


class AsyncEventMessageHandler(Protocol):
    async def handle(self, message: EventMessage) -> None: ...


class IMessageQueue(Protocol):
    def enqueue(self, message: EventMessage) -> None: ...
    def dequeue(self) -> EventMessage | None: ...
    def drain(self) -> list[EventMessage]: ...
    def size(self) -> int: ...


class IAsyncMessageQueue(Protocol):
    async def enqueue(self, message: EventMessage) -> None: ...
    async def dequeue(self) -> EventMessage: ...
    def size(self) -> int: ...


class IEventBus(Protocol):
    def subscribe(self, event_name: str, handler: EventMessageHandler) -> None: ...
    def unsubscribe(self, event_name: str, handler: EventMessageHandler) -> None: ...
    def publish(self, message: EventMessage) -> None: ...
    def publish_many(self, messages: Sequence[EventMessage]) -> None: ...


class IAsyncEventBus(Protocol):
    def subscribe(
        self,
        event_name: str,
        handler: AsyncEventMessageHandler | EventMessageHandler,
    ) -> None: ...
    def unsubscribe(
        self,
        event_name: str,
        handler: AsyncEventMessageHandler | EventMessageHandler,
    ) -> None: ...
    async def publish(self, message: EventMessage) -> None: ...
    async def publish_many(self, messages: Sequence[EventMessage]) -> None: ...
    async def start(self) -> None: ...
    async def stop(self) -> None: ...


class IAsyncExceptionBus(Protocol):
    def subscribe(
        self,
        event_name: str,
        handler: AsyncEventMessageHandler | EventMessageHandler,
    ) -> None: ...
    def unsubscribe(
        self,
        event_name: str,
        handler: AsyncEventMessageHandler | EventMessageHandler,
    ) -> None: ...
    async def publish(self, message: ExceptionEvent) -> None: ...
    async def publish_many(self, messages: Sequence[ExceptionEvent]) -> None: ...
    async def start(self) -> None: ...
    async def stop(self) -> None: ...
